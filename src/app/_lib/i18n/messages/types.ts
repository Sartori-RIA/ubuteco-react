type JoinKeys<P extends string, K extends string> = P extends "" ? K : `${P}.${K}`;

export type MessageKey<T, Prefix extends string = ""> = T extends string
  ? Prefix
  : T extends object
    ? {
        [K in keyof T & string]: MessageKey<T[K], JoinKeys<Prefix, K>>;
      }[keyof T & string]
    : Prefix;

export type TranslationKey = MessageKey<MessageCatalog>;
